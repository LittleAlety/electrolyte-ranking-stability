def test_index_html_managed_regions_match_the_generator():
    """The --check discipline, run in-process: a stale region is a failure."""
    html = (DOCS / "index.html").read_text(encoding="utf-8")
    rendered = dict(site.managed_blocks(_payload()))
    assert set(rendered) == set(MANAGED_BLOCKS), (
        "the builder and the page disagree about which regions exist")
    for name in MANAGED_BLOCKS:
        assert _managed_region(html, name).strip("\n") == rendered[name].strip("\n"), (
            "index.html region %r is stale; rerun scripts/build_terminal_site.py" % name)


def test_argument_timeline_has_one_row_per_stage_with_a_link():
    html = (DOCS / "index.html").read_text(encoding="utf-8")
    weeks = _payload()["weeks"]
    block = _managed_region(html, "argument-timeline")
    rows = re.findall(r'<li class="tl-row" data-week="(\d+)">(.*?)</li>', block, re.S)
    assert rows, "the timeline rendered no rows"
    assert {int(n) for n, _ in rows} == {w["n"] for w in weeks}, (
        "the timeline does not cover every stage in the payload")
    assert [int(n) for n, _ in rows] == [w["n"] for w in weeks], (
        "the timeline is not in stage order")
    for number, row in rows:
        assert re.search(r">Week ", row), "stage %s row lost its week label" % number
        hrefs = re.findall(r'href="([^"]+)"', row)
        assert any("/blob/main/" in h for h in hrefs), (
            "stage %s row carries no report link" % number)


def test_index_html_static_numbers_track_the_payload():
    """What a crawler or a JS-off reader sees must equal the payload's truth."""
    payload = _payload()
    counts = payload["counts"]
    last = payload["weeks"][-1]
    html = (DOCS / "index.html").read_text(encoding="utf-8")

    expected = {
        "js-weeks": str(counts["weeks"]),
        "js-figures": str(counts["figures"]),
        "js-orca": str(counts["orca_out"]),
        "js-tests": str(counts["tests_passed"]),
        "js-latest-week": str(last["n"]),
        "js-latest": "Week %d / %s" % (last["n"], last["stage"]),
    }
    seen = {key: [] for key in expected}
    for match in re.finditer(r'<span class="(js-[a-z-]+)">([^<]*)</span>', html):
        if match.group(1) in seen:
            seen[match.group(1)].append(match.group(2))
    for key, want in sorted(expected.items()):
        assert seen[key], "index.html renders no %s value" % key
        for got in seen[key]:
            assert got == want, "%s shows %r but the payload says %r" % (key, got, want)

    meta = re.search(r'<meta name="description" content="([^"]*)"', html)
    assert meta, "index.html lost its meta description"
    assert "%d 条阶段记录" % counts["weeks"] in meta.group(1)
    assert "%d 张图" % counts["figures"] in meta.group(1)


def test_noscript_fallback_counts_track_the_payload():
    html = (DOCS / "index.html").read_text(encoding="utf-8")
    block = _managed_region(html, "static-fallbacks")
    assert "<noscript>" in block and "</noscript>" in block
    payload = _payload()
    assert ('<span class="js-weeks">%d</span>' % payload["counts"]["weeks"]) in block
    for gate in payload["gates"]:
        assert gate["status"] in block, "the noscript fallback omits " + gate["status"]
        for blocker in gate["blockers"]:
            # Blockers carry chemistry like "tau_b=0.4286 < 0.90" and are escaped
            # for the markup, so compare against the escaped form.
            escaped = (blocker.replace("&", "&amp;").replace("<", "&lt;")
                       .replace(">", "&gt;"))
            assert escaped in block, "the noscript fallback omits a gate blocker"


