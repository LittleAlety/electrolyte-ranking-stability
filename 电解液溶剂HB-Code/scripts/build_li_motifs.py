# site generation (frozen rule, steps 2-4)
# ---------------------------------------------------------------------------
def monodentate_sites(donors, symbols, neighbours, coords):
    sites = []
    for index in donors:
        direction = lone_pair_direction(index, symbols, neighbours, coords)
        if direction is None:
            continue
        distance = PLACEMENT_DISTANCE.get(symbols[index], 2.00)
        sites.append(
            {
                "placement": "monodentate",
                "donors": (index,),
                "target_distance": distance,
                "position": coords[index] + distance * direction,
            }
        )
    return sites


def bidentate_sites(donors, symbols, neighbours, coords):
    """Li+ equidistant from two donors, on the bisector side facing outward."""

    centroid = coords.mean(axis=0)
    sites = []
    for position, first in enumerate(donors):
        for second in donors[position + 1 :]:
            separation = float(np.linalg.norm(coords[first] - coords[second]))
            if separation > BIDENTATE_MAX_DONOR_DISTANCE:
                continue
            first_dir = lone_pair_direction(first, symbols, neighbours, coords)
            second_dir = lone_pair_direction(second, symbols, neighbours, coords)
            if first_dir is None or second_dir is None:
                continue
            bisector = unit(first_dir + second_dir)
            axis = unit(coords[second] - coords[first])
            if bisector is None or axis is None:
                continue
            perpendicular = unit(bisector - float(np.dot(bisector, axis)) * axis)
            middle = 0.5 * (coords[first] + coords[second])
            target = 0.5 * (
                PLACEMENT_DISTANCE.get(symbols[first], 2.00)
                + PLACEMENT_DISTANCE.get(symbols[second], 2.00)
            )
            half = 0.5 * separation
            if perpendicular is None or half >= target:
                # The two donors are too far apart to bridge one Li+ at a
                # chemical Li-donor distance. The candidate is kept anyway, sat
                # on the perpendicular bisector, and the xTB pre-opt decides
                # whether it survives or collapses onto a monodentate minimum.
                candidate = middle
                placement = "bidentate_long"
            else:
                offset = math.sqrt(target * target - half * half)
                placements = [
                    middle + offset * perpendicular,
                    middle - offset * perpendicular,
                ]
                candidate = max(
                    placements,
                    key=lambda point: float(np.linalg.norm(point - centroid)),
                )
                placement = "bidentate"
            sites.append(
                {
                    "placement": placement,
                    "donors": (first, second),
                    "target_distance": target,
                    "position": candidate,
                }
            )
    return sites


def read_esp_grid(path: Path) -> list:
    """(sigma, position) for every surface segment of an xtb --esp COSMO file.

    Columns are: index, type, x, y, z, sigma, area, sigma, 0.0. sigma is the
    segment charge density, i.e. the electrostatic potential on the vdW grid up
    to the constant factor xtb applies when it prints its ESP report; the
    regression test pins that factor down against a real xTB output.
    """

    points = []
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        parts = line.split()
        if len(parts) < 8 or not parts[0].isdigit():
            continue
        try:
            sigma = float(parts[5])
            position = np.asarray([float(parts[2]), float(parts[3]), float(parts[4])])
        except ValueError:
            continue
        points.append((sigma, position))
    points.sort(key=lambda item: item[0])
    return points


def esp_sites(parent_xyz: Path, donors, symbols, coords, executable, workdir: Path) -> list:
    """Supplement the sites with the molecular ESP minima (frozen rule step 4).

    ``xtb --esp`` writes ``xtb_esp.cosmo``, whose surface segments carry the
    electrostatic potential on the vdW grid in their sigma column (xtb prints
    the same numbers scaled by ten in its own ESP report; the regression test
    pins that factor down). The most negative sigma is therefore the most
    attractive point for a cation on that grid. Its position is mapped back to
    the nearest donor and turned into one more initial site, so a donor whose
    lone-pair direction was mis-guessed can still be recovered.
    """

    if executable is None:
        return []
    workdir.mkdir(parents=True, exist_ok=True)
    probe = workdir / parent_xyz.name
    probe.write_text(
        parent_xyz.read_text(encoding="utf-8"), encoding="utf-8", newline=chr(10)
    )
    completed = toolchain.run_command(
        executable,
        [parent_xyz.name, "--esp", "--gfn", "2"],
        cwd=workdir,
        timeout_seconds=900.0,
        environment=xtb.xtb_thread_environment(),
    )
    cosmo = workdir / "xtb_esp.cosmo"
    if not cosmo.exists():
        text = (completed.stdout or "") + (completed.stderr or "")
        (workdir / "esp.log").write_text(text, encoding="utf-8", newline=chr(10))
        return []
    points = read_esp_grid(cosmo)
    if not points:
        return []
    sites = []
    seen = set()
    for sigma, position in points[:24]:
        distances = [float(np.linalg.norm(position - coords[index])) for index in donors]
        donor_index = donors[int(np.argmin(distances))]
        direction = unit(position - coords[donor_index])
        if direction is None:
            continue
        key = (
            donor_index,
            int(round(float(direction[0]) * 4)),
            int(round(float(direction[1]) * 4)),
            int(round(float(direction[2]) * 4)),
        )
        if key in seen:
            continue
        seen.add(key)
        distance = PLACEMENT_DISTANCE.get(symbols[donor_index], 2.00)
        sites.append(
            {
                "placement": "esp_min",
                "donors": (donor_index,),
                "target_distance": distance,
                "position": coords[donor_index] + distance * direction,
                "sigma": sigma,
            }
        )
        if len(sites) >= 3:
            break
    return sites


def merge_sites(sites):
    """Drop sites that sit on top of each other (frozen rule step 6, first pass)."""

    merged = []
    for site in sites:
        if any(
            float(np.linalg.norm(site["position"] - kept["position"])) < SITE_MERGE_DISTANCE
            for kept in merged
        ):
            continue
        merged.append(site)
    return merged

# ---------------------------------------------------------------------------
# xTB pre-optimisation (step 5) and QC
# ---------------------------------------------------------------------------
def parent_bonds_intact(symbols_h, neighbours, coords) -> bool:
    """True when no covalent bond of the parent molecule was broken."""

    for index in range(len(symbols_h)):
        for other, _ in neighbours[index]:
            if other <= index:
                continue
            limit = BOND_INTACT_FACTOR * (
                COVALENT_RADIUS.get(symbols_h[index], 0.8)
                + COVALENT_RADIUS.get(symbols_h[other], 0.8)
            )
            if float(np.linalg.norm(coords[index] - coords[other])) > limit:
                return False
    return True


def relax_candidate(name, parent_xyz, site, args, index) -> dict:
    """One GFN2-xTB optimisation of the [Li M]+ complex started from ``site``."""

    symbols_h, coords_h = read_xyz(parent_xyz)
    symbols = list(symbols_h) + ["Li"]
    coords = np.vstack([coords_h, site["position"]])
    label = name + "_cand%02d" % index
    workdir = Path(args.scratch) / name / label
    workdir.mkdir(parents=True, exist_ok=True)
    xyz_path = workdir / (label + ".xyz")
    write_xyz(xyz_path, symbols, coords, label + " " + site["placement"])
    started = time.perf_counter()
    payload = {
        "candidate_id": "c%02d" % index,
        "placement": site["placement"],
        "donor_indices": list(site["donors"]),
        "target_distance": site["target_distance"],
    }
    try:
        result = xtb.run_xtb(
            args.xtb_executable,
            xtb.JOB_OPTIMIZE,
            input_name=xyz_path.name,
            charge=1,
            multiplicity=1,
            cwd=workdir,
            timeout_seconds=args.timeout,
            required=(),
        )
    except Exception as exc:  # noqa: BLE001 - a failed pre-opt is a result, not a crash
        payload.update(
            {
                "status": "execution_failed",
                "energy_eh": None,
                "optimized": None,
                "qc_flags": ["geometry_failed"],
                "error": repr(exc),
                "seconds": round(time.perf_counter() - started, 2),
            }
        )
        return payload
    raw_path = workdir / (label + "_opt.out")
    raw_path.write_text(result.raw_output, encoding="utf-8", newline=chr(10))
    optimized_path = workdir / "xtbopt.xyz"
    optimized = None
    if optimized_path.exists():
        _, optimized = read_xyz(optimized_path)
    payload.update(
        {
            "status": "ok" if result.normal_termination else "abnormal_termination",
            "energy_eh": result.total_energy_eh,
            "optimized": optimized,
            "qc_flags": list(result.qc_flags),
            "error": "",
            "seconds": round(time.perf_counter() - started, 2),
        }
    )
    return payload


def candidate_record(row, symbols_h, neighbours, site, payload, rule_check, global_donors):
    """Everything the CSV needs for one candidate, including the QC verdict."""

    donors = list(site["donors"])
    optimized = payload.get("optimized")
    flags = list(payload.get("qc_flags") or [])
    contacts = []
    donor_contacts = []
    li_min = None
    intact = None
    if optimized is not None:
        distances = [
            float(np.linalg.norm(optimized[-1] - optimized[index]))
            for index in range(len(symbols_h))
        ]
        contacts = [index for index, value in enumerate(distances) if value <= CONTACT_CUTOFF]
        li_min = min(distances)
        intact = parent_bonds_intact(symbols_h, neighbours, optimized[: len(symbols_h)])
        if not intact:
            flags.append("dissociated_optimized_product")
        # Connectivity is the set of DONOR atoms that actually carry Li, not the
        # set the initial site asked for: a monodentate start that slides into a
        # chelate has reached the same motif as the chelate start, and the two
        # must be recorded as one motif rather than as two "different" ones.
        donor_contacts = [index for index in contacts if index in set(global_donors)]
        if not donor_contacts:
            flags.append("no_intact_minimum_found")
        elif set(donor_contacts) != set(donors):
            flags.append("motif_switch")
    return {
        "mol_id": row["mol_id"],
        "name": row["name"],
        "family": row.get("family", ""),
        "candidate_id": payload["candidate_id"],
        "placement": payload["placement"],
        "donor_indices": ";".join(str(index) for index in donors),
        "donor_symbols": "".join(symbols_h[index] for index in donors),
        "target_distance_a": "%.3f" % payload["target_distance"],
        "preopt_status": payload["status"],
        "preopt_energy_eh": payload["energy_eh"],
        "preopt_energy_rel_kj": None,
        "n_donor_contacts": len(donor_contacts),
        "contact_donor_indices": ";".join(str(index) for index in donor_contacts),
        "li_min_distance_a": li_min,
        "parent_bonds_intact": intact,
        "kept": False,
        "dedup_reason": "",
        "motif_id": "",
        "motif_path": "",
        "donor_rule_check": rule_check,
        "qc_flags": ";".join(sorted(set(flags))),
        "seconds": payload["seconds"],
        "error": payload["error"],
        "optimized": optimized,
        "contacts": tuple(sorted(contacts)),
        "donor_contacts": tuple(sorted(donor_contacts)),
        "donors": tuple(sorted(donors)),
    }

# ---------------------------------------------------------------------------
# dedup (frozen rule step 6) and selection (step 7)
# ---------------------------------------------------------------------------
def select_motifs(records, energy_window_kj: float, max_motifs: int):
    """Keep the lowest-energy candidate per Li connectivity, then the window survivors."""

    usable = [
        record
        for record in records
        if record["preopt_status"] == "ok"
        and record["optimized"] is not None
        and record["preopt_energy_eh"] is not None
        and record["donor_contacts"]
        and record["parent_bonds_intact"]
    ]
    usable_ids = {id(record) for record in usable}
    for record in records:
        if id(record) in usable_ids:
            continue
        if record["preopt_status"] != "ok":
            record["dedup_reason"] = "preopt_not_ok"
        elif record["optimized"] is None:
            record["dedup_reason"] = "no_optimized_geometry"
        elif record["preopt_energy_eh"] is None:
            record["dedup_reason"] = "no_energy"
        elif not record["donor_contacts"]:
            record["dedup_reason"] = "no_donor_contact"
        else:
            record["dedup_reason"] = "parent_bonds_broken"

    best_by_connectivity = defaultdict(list)
    for record in usable:
        best_by_connectivity[record["donor_contacts"]].append(record)
    survivors = []
    for group in best_by_connectivity.values():
        group.sort(key=lambda item: item["preopt_energy_eh"])
        winner = group[0]
        for loser in group[1:]:
            first = loser["optimized"][:-1]
            second = winner["optimized"][:-1]
            same_geometry = (
                first.shape == second.shape and kabsch_rmsd(first, second) < 0.25
            )
            loser["dedup_reason"] = (
                "duplicate_geometry_of_" + winner["candidate_id"]
                if same_geometry
                else "duplicate_connectivity_of_" + winner["candidate_id"]
            )
        survivors.append(winner)

    survivors.sort(key=lambda item: item["preopt_energy_eh"])
    if not survivors:
        return []
    reference = survivors[0]["preopt_energy_eh"]
    kept = []
    for record in survivors:
        relative = (record["preopt_energy_eh"] - reference) * EH_TO_KJ
        record["preopt_energy_rel_kj"] = relative
        if relative > energy_window_kj:
            record["dedup_reason"] = "above_energy_window"
        elif len(kept) >= max_motifs:
            record["dedup_reason"] = "beyond_max_motifs"
        else:
            record["kept"] = True
            record["motif_id"] = "m%d" % (len(kept) + 1)
            kept.append(record)
    return kept


