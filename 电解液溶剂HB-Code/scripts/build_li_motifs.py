def read_xyz(path: Path):
    """Return (symbols, coords) from an XYZ file, both in file order."""

    lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
    index = 0
    while index < len(lines) and not lines[index].strip():
        index += 1
    count = int(lines[index].strip())
    symbols = []
    coords = []
    for line in lines[index + 2 : index + 2 + count]:
        parts = line.split()
        symbols.append(parts[0])
        coords.append([float(parts[1]), float(parts[2]), float(parts[3])])
    return symbols, np.asarray(coords, dtype=float)


def format_xyz(symbols, coords, comment: str) -> str:
    lines = [str(len(symbols)), comment]
    for symbol, (x, y, z) in zip(symbols, coords):
        lines.append("%-2s %16.10f %16.10f %16.10f" % (symbol, x, y, z))
    return chr(10).join(lines) + chr(10)


def write_xyz(path: Path, symbols, coords, comment: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(format_xyz(symbols, coords, comment), encoding="utf-8", newline=chr(10))


def unit(vector):
    norm = float(np.linalg.norm(vector))
    if norm < 1e-9:
        return None
    return vector / norm


def kabsch_rmsd(first, second) -> float:
    """Heavy-atom RMSD after optimal superposition (rotation only, no reflection)."""

    first_centred = first - first.mean(axis=0)
    second_centred = second - second.mean(axis=0)
    covariance = first_centred.T @ second_centred
    left, _, right = np.linalg.svd(covariance)
    determinant = np.sign(np.linalg.det(left @ right))
    correction = np.diag([1.0, 1.0, determinant])
    rotated = first_centred @ (left @ correction @ right)
    return float(np.sqrt(np.mean(np.sum((rotated - second_centred) ** 2, axis=1))))


