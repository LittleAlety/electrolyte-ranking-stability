#!/usr/bin/env python
"""Stage 5 / T4 step 1 -- Li+ coordination motif enumeration for the C1 state.

This module implements, in the order written there, the frozen rule
``conformers_and_states.li_motif_generation`` of
``config/scientific_definitions.yaml`` (frozen: true, do not edit):

    1. identify O/N/S/P donor atoms
    2. one monodentate Li+ site per donor
    3. bidentate candidates for the geometrically allowed donor pairs
    4. supplement with the molecular ESP minima
    5. GFN2-xTB pre-optimisation
    6. dedup by Li-donor connectivity / key distances / structural similarity / energy
    7. the surviving low-energy motifs are the ones that go to DFT

Why this is code and not judgement
----------------------------------
Motif enumeration is the most subjective step of Stage 5, so it is the step that
has to be reproducible: every candidate below is generated by a written-down
rule, pre-optimised with the same frozen xTB used everywhere else, and recorded
together with the numbers that decided its fate. A candidate that is generated
and then dropped is still written to the CSV -- dropping it silently would be
the same class of error as deleting a failed SCF.

Donor rule
----------
An atom is a donor when it can offer a lone pair to Li+:

* every oxygen (carbonyl, ether, sulfoxide-O, sulfone-O, phosphate-O);
* a nitrogen with a triple bond (nitrile) or with at most two heavy neighbours;
* sulfur only when it carries no double-bonded oxygen, i.e. a sulfone or
  sulfoxide sulfur is NOT a donor -- its oxygens are;
* phosphorus only when it carries no double-bonded oxygen, i.e. a phosphate
  phosphorus is not a donor -- its oxygens are.

The derived donor elements are compared per molecule with the frozen
``donor_atoms`` column of ``data/metadata/core_set.csv`` and the verdict is
stored in every row (``donor_rule_check``), so a disagreement is visible.

Geometry convention
-------------------
All distances are Angstrom. The parent geometry is always the shared G1
(GFN2-xTB) geometry of ``outputs/_week3_scratch``; motif work never rebuilds it,
so C0 and C1 are anchored on the same parent structure.

Outputs
-------
``structures/li_motifs/<NAME>_m<k>.xyz``   one file per surviving motif
``outputs/week5/li_motif_generation.csv``  one row per (molecule, candidate)
``outputs/week5/li_motif_generation.json`` run record (versions, counts, rule)
``outputs/week5/li_motif_generation.md``   human-readable motif table
"""

