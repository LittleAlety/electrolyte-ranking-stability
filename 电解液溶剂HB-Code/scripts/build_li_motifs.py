def heavy_graph(smiles: str):
    """(symbols, neighbours) of the heavy atoms, in SMILES order.

    ``scripts/run_xtb_job.build_geometry`` embeds with ``Chem.AddHs`` and RDKit
    keeps the heavy atoms in SMILES order with hydrogens appended, so heavy atom
    i of the SMILES graph is atom i of the stored XYZ. That is asserted in
    ``check_heavy_order`` rather than trusted.
    """

    from rdkit import Chem

    molecule = Chem.MolFromSmiles(smiles)
    if molecule is None:
        raise ValueError("RDKit could not parse SMILES " + repr(smiles))
    symbols = [atom.GetSymbol() for atom in molecule.GetAtoms()]
    neighbours = defaultdict(list)
    for bond in molecule.GetBonds():
        first = bond.GetBeginAtomIdx()
        second = bond.GetEndAtomIdx()
        order = bond.GetBondTypeAsDouble()
        neighbours[first].append((second, order))
        neighbours[second].append((first, order))
    return symbols, neighbours


def check_heavy_order(symbols_h, smiles: str) -> None:
    expected, _ = heavy_graph(smiles)
    if list(symbols_h[: len(expected)]) != expected:
        raise ValueError(
            "XYZ heavy-atom order does not match the SMILES graph of "
            + smiles
            + ": "
            + "".join(symbols_h[: len(expected)])
            + " vs "
            + "".join(expected)
        )


def find_donors(symbols_h, neighbours) -> list:
    """Indices of heavy atoms that can offer a lone pair (see module docstring)."""

    donors = []
    for index, symbol in enumerate(symbols_h):
        if symbol == "O":
            donors.append(index)
        elif symbol == "N":
            orders = [order for _, order in neighbours[index]]
            if len(neighbours[index]) <= 2 or any(order >= 3 for order in orders):
                donors.append(index)
        elif symbol in ("S", "P"):
            double_to_oxygen = any(
                symbols_h[other] == "O" and order >= 2
                for other, order in neighbours[index]
            )
            if not double_to_oxygen:
                donors.append(index)
    return donors


def donor_rule_check(symbols_h, donors, metadata_tokens: str) -> str:
    """Compare the derived donor elements with the frozen ``donor_atoms`` column."""

    derived = sorted({symbols_h[index] for index in donors})
    expected = sorted(
        {
            token.strip()[0]
            for token in (metadata_tokens or "").split(";")
            if token.strip()
        }
    )
    if derived == expected:
        return "elements_match"
    return "elements_mismatch derived=" + "".join(derived) + " metadata=" + "".join(expected)


def lone_pair_direction(index, symbols, neighbours, coords):
    """Unit vector pointing away from the donor's bonded neighbours."""

    bonded = [other for other, _ in neighbours[index]]
    if not bonded:
        return None
    vectors = [unit(coords[other] - coords[index]) for other in bonded]
    if any(vector is None for vector in vectors):
        return None
    return unit(-np.sum(vectors, axis=0))

